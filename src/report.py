"""Aggregate results/raw/*.json into mean ± std tables (results/summary.md, summary.csv) and plots.

Model selection uses validation only: the headline NCRC configuration is the one with the best mean
validation AUPRC over seeds; test numbers of every configuration are still reported (ablation table).
"""
import json
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from common import NOISE_LEVELS, RESULTS_DIR, SEEDS, SHOTS_PER_EXECUTION as SHOTS

METRICS = ["AUPRC", "AUROC", "Spearman rho", "precision", "recall", "F1", "MCC"]
LEVELS = [0.0, *NOISE_LEVELS]


def load():
    runs = defaultdict(dict)
    for f in sorted((RESULTS_DIR / "raw").glob("*.json")):
        r = json.loads(f.read_text())
        runs[r["tag"]][r["seed"]] = r
    return runs


def protocol_frame(runs, tag):
    rows = []
    for seed, r in runs[tag].items():
        prot = r["protocol"]
        if len(prot) == 1:  # classical model: same scores at every noise level
            prot = [{**prot[0], "p": p, "Spearman rho": 1.0} for p in LEVELS]
        rows += [{**row, "seed": seed} for row in prot]
    return pd.DataFrame(rows)


def mean_std(df):
    g = df.groupby("p")[METRICS]
    m, s = g.mean(), g.std(ddof=1)
    return m, s


def fmt(m, s):
    return f"{m:.3f} ± {s:.3f}"


def main():
    runs = load()
    tags = sorted(runs)
    out, csv_rows = ["# Results summary (generated by `src/report.py`)\n"], []
    for tag in tags:
        if set(runs[tag]) != set(SEEDS):
            out.append(f"> ⚠️ `{tag}` has seeds {sorted(runs[tag])}, expected {SEEDS}\n")
    # ---- per-model protocol tables
    summary = {}
    for tag in tags:
        m, s = mean_std(protocol_frame(runs, tag))
        summary[tag] = (m, s)
        out.append(f"\n## {tag}\n\n| p | " + " | ".join(METRICS) + " |\n|" + "---|" * (len(METRICS) + 1))
        for p in m.index:
            out.append(f"| {p} | " + " | ".join(fmt(m.loc[p, k], s.loc[p, k]) for k in METRICS) + " |")
            csv_rows.append({"model": tag, "p": p, **{f"{k} mean": m.loc[p, k] for k in METRICS}, **{f"{k} std": s.loc[p, k] for k in METRICS}})
        first = next(iter(runs[tag].values()))
        if "ledger" in first:
            led = first["ledger"]
            res = first["resources"]
            val = [r["best_val_auprc_train_subset"] for r in runs[tag].values()]
            out.append(f"\n- wires {res['n_wires']}, noise locations {res['noise_locations']}, gates {res['gate_counts']}, trainable params {res['trainable_params']}")
            out.append(f"- ledger: {led['executions_per_sample']} executions/sample × {led['n_train']} × {led['epochs']} epochs = {led['train_executions']:,} train; "
                       f"{led['val_passes']} val passes × {led['val_rows']:,} rows = {led['val_executions']:,} val; "
                       f"total {led['total_executions']:,} executions = {led['total_shots']:,} shots")
            out.append(f"- validation AUPRC used for epoch selection (noiseless): {np.mean(val):.3f} ± {np.std(val, ddof=1):.3f}")
    # ---- headline table at p = 0.01 / 0.05 + ledger
    out.append("\n## Headline: test AUPRC / Spearman ρ / F1 at p = 0.01 and 0.05, and cost\n")
    out.append("| model | AUPRC p=0.01 | AUPRC p=0.05 | ρ p=0.05 | F1 p=0.05 | MCC p=0.05 | noise loc. | train+val executions |\n|---|---|---|---|---|---|---|---|")
    for tag in tags:
        m, s = summary[tag]
        first = next(iter(runs[tag].values()))
        nl = first["resources"]["noise_locations"] if "resources" in first else "–"
        ex = f"{first['ledger']['total_executions']:,}" if "ledger" in first else "–"
        out.append(f"| {tag} | {fmt(m.loc[0.01, 'AUPRC'], s.loc[0.01, 'AUPRC'])} | {fmt(m.loc[0.05, 'AUPRC'], s.loc[0.05, 'AUPRC'])} | "
                   f"{fmt(m.loc[0.05, 'Spearman rho'], s.loc[0.05, 'Spearman rho'])} | {fmt(m.loc[0.05, 'F1'], s.loc[0.05, 'F1'])} | "
                   f"{fmt(m.loc[0.05, 'MCC'], s.loc[0.05, 'MCC'])} | {nl} | {ex} |")
    # ---- finite-shot stress test (src/shots.py): mean over seeds of the per-seed mean over shot draws
    shot_rows = [{"model": r["model"], "seed": r["seed"], **row}
                 for f in sorted((RESULTS_DIR / "shots").glob("*.json")) for r in [json.loads(f.read_text())] for row in r["rows"]]
    if shot_rows:
        per_seed = pd.DataFrame(shot_rows).groupby(["model", "p", "seed"]).mean(numeric_only=True)
        agg = per_seed.groupby(["model", "p"]).agg(["mean", "std"])
        out.append(f"\n## Finite shots: test scores estimated from {SHOTS} shots per transaction\n")
        out.append("| model | p | AUPRC exact | AUPRC with shots | Spearman ρ (shots vs noiseless exact) |\n|---|---|---|---|---|")
        for (model, p), row in agg.iterrows():
            out.append(f"| {model} | {p} | {fmt(row[('AUPRC exact', 'mean')], row[('AUPRC exact', 'std')])} | "
                       f"{fmt(row[('AUPRC shots', 'mean')], row[('AUPRC shots', 'std')])} | "
                       f"{fmt(row[('Spearman rho shots vs clean', 'mean')], row[('Spearman rho shots vs clean', 'std')])} |")
    (RESULTS_DIR / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    pd.DataFrame(csv_rows).to_csv(RESULTS_DIR / "summary.csv", index=False)
    # ---- plots
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.2))
    for tag in tags:
        m, s = summary[tag]
        x = [str(p) for p in m.index]
        style = "--" if tag == "logreg" else "-"
        for ax, k in zip(axes, ["AUPRC", "Spearman rho", "F1"]):
            ax.errorbar(x, m[k], yerr=s[k], marker="o", capsize=3, linestyle=style, label=tag)
    for ax, k in zip(axes, ["Test AUPRC", "Spearman ρ (noisy vs noiseless test scores)", "Test F1 (threshold chosen under noise)"]):
        ax.set_title(k)
        ax.set_xlabel("depolarizing probability p per gate")
        ax.grid(alpha=0.3)
    axes[0].legend(fontsize=7)
    plt.tight_layout()
    plt.savefig(RESULTS_DIR / "metrics_vs_noise.png", dpi=150)
    print((RESULTS_DIR / "summary.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
